<?php

declare(strict_types=1);

namespace MailerPress\Services;

\defined('ABSPATH') || exit;

/**
 * Protects MailerPress storage directories in uploads (contact exports, legacy log
 * directories) and removes the legacy world-readable wp-content/mailerpress-logs/.
 *
 * MailerPress no longer writes debug log files.
 */
final class DebugFileLogger
{
    private const DIR_SLUG = 'mailerpress-logs';

    /**
     * Deny direct HTTP access to a directory (Apache 2.2/2.4) and prevent listings.
     */
    public static function protectDirectory(string $directory): void
    {
        $directory = untrailingslashit($directory);

        $htaccess = $directory . '/.htaccess';
        if (!file_exists($htaccess)) {
            @file_put_contents(
                $htaccess,
                "# Generated by MailerPress: never serve these files.\n"
                . "<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n"
                . "<IfModule !mod_authz_core.c>\n    Order deny,allow\n    Deny from all\n</IfModule>\n"
            );
        }

        $index = $directory . '/index.php';
        if (!file_exists($index)) {
            @file_put_contents($index, "<?php\n// Silence is golden.\n");
        }
    }

    /**
     * Remove the legacy world-readable log directory created by previous versions
     * (wp-content/mailerpress-logs/). Only MailerPress log files are removed.
     */
    public static function purgeLegacyDirectory(): void
    {
        $legacy = untrailingslashit(WP_CONTENT_DIR) . '/' . self::DIR_SLUG;

        if (!is_dir($legacy)) {
            return;
        }

        foreach ((array) glob($legacy . '/*.log') as $file) {
            if (\is_string($file) && is_file($file)) {
                @unlink($file);
            }
        }

        foreach (['.htaccess', 'index.php', 'index.html'] as $extra) {
            if (is_file($legacy . '/' . $extra)) {
                @unlink($legacy . '/' . $extra);
            }
        }

        @rmdir($legacy);
    }

    /**
     * Make sure the shared uploads/mailerpress-logs directory used by older import and repair
     * logs cannot be listed or served.
     */
    public static function protectLegacyUploadsDirectory(): void
    {
        $uploads = wp_upload_dir(null, false);
        if (!empty($uploads['error']) || empty($uploads['basedir'])) {
            return;
        }

        $directory = trailingslashit($uploads['basedir']) . self::DIR_SLUG;
        if (is_dir($directory)) {
            self::protectDirectory($directory);
        }
    }
}
